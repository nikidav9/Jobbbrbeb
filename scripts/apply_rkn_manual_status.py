#!/usr/bin/env python3
from pathlib import Path

path = Path('docs/ручные-шаги.md')
text = path.read_text(encoding='utf-8')

old_v1 = '''### В1. Уведомление об обработке персональных данных

Вы оператор персональных данных: собираете имя, телефон, возраст, переписку.
Уведомление подаётся до начала обработки — то есть срок уже идёт.

1. Портал персональных данных РКН: https://pd.rkn.gov.ru/
2. Форма уведомления оператора → заполнить и отправить
3. Подписать усиленной квалифицированной подписью либо отправить бумажный
   вариант в территориальное управление
'''
new_v1 = '''### В1. Уведомление об обработке персональных данных — подано ✅

Основное уведомление **уже направлено** 08.09.2026. Обращение
**№ 02-11-33294/77**, срок рассмотрения — **02.10.2026**.

До этого срока ничего повторно подавать не нужно. Следующий ручной шаг —
проверить результат рассмотрения в РКН и, если ведомство запросит уточнения,
ответить на них. До получения результата формулируем статус именно как
«направлено», а не «зарегистрировано».
'''

old_v2 = '''### В2. Отдельное уведомление о передаче за границу

Часть данных всё ещё уходит за пределы России: Telegram, доставка уведомлений
на устройства, геокодирование адресов. По 152-ФЗ трансграничная передача
уведомляется отдельно от В1.

1. Тот же портал, отдельная форма
2. Указать страны. Германия входит в перечень приказа РКН №128, США — нет
3. Для стран не из перечня — дождаться окончания срока рассмотрения, прежде чем
   передавать дальше
'''
new_v2 = '''### В2. Отдельное уведомление о передаче за границу — подано ✅

Дополнительное уведомление о трансграничной передаче **уже направлено**
14.09.2026. Обращение **№ 02-11-34185/77**, срок рассмотрения —
**08.10.2026**.

Повторно подавать форму не нужно. До окончания рассмотрения сохраняем текущие
минимизированные зарубежные передачи и после 08.10 проверяем результат РКН;
если придёт запрос или ограничение, действуем по нему, а не создаём новое
уведомление вслепую.
'''

for label, old, new in [('В1', old_v1, new_v1), ('В2', old_v2, new_v2)]:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f'{label}: expected one exact block, found {count}')
    text = text.replace(old, new, 1)

# Guard against accidentally changing the already-correct lawyer/manual sections.
if '### В3. Показать документы юристу' not in text:
    raise SystemExit('В3 anchor missing after patch')
if text.count('02-11-33294/77') != 1 or text.count('02-11-34185/77') != 1:
    raise SystemExit('RKN notice numbers must each appear exactly once in manual steps')

path.write_text(text, encoding='utf-8')
print('RKN manual status patch applied')
