-- Чат поддержки: сначала помощник по базе знаний, затем — оператор по запросу.
--
-- Важно: ответы помощника не приходят с клиента. Клиент отправляет только
-- вопрос, а PHP-прокси сам подбирает статью из этой закрытой таблицы и пишет
-- ответ в историю. Пользователь не может подделать сообщение оператора.
--
-- Оператор появляется в дашборде только после явного «Позвать оператора».
-- Старые обращения сохраняем как вызовы оператора, чтобы история не пропала.

alter table public.jm_support_messages
  add column if not exists sender text;

update public.jm_support_messages
   set sender = case when direction = 'in' then 'user' else 'operator' end
 where sender is null;

alter table public.jm_support_messages
  alter column sender set default 'user',
  alter column sender set not null;

alter table public.jm_support_messages
  drop constraint if exists jm_support_messages_sender_check;

alter table public.jm_support_messages
  add constraint jm_support_messages_sender_check
  check (sender in ('user', 'assistant', 'operator', 'system'));

alter table public.jm_support_threads
  add column if not exists operator_requested_at timestamptz,
  add column if not exists operator_request_text text;

update public.jm_support_threads t
   set operator_requested_at = coalesce(t.operator_requested_at, t.updated_at)
 where t.operator_requested_at is null
   and exists (
     select 1 from public.jm_support_messages m where m.user_id = t.user_id
   );

create table if not exists public.jm_support_knowledge (
  id          text primary key,
  role        text not null default 'all'
              check (role in ('all', 'worker', 'employer')),
  question    text not null,
  answer      text not null,
  keywords    text[] not null default '{}',
  priority    integer not null default 100,
  active      boolean not null default true,
  updated_at  timestamptz not null default now()
);

alter table public.jm_support_knowledge enable row level security;
revoke all on public.jm_support_knowledge from anon, authenticated;

