-- Из агрегаторов остаётся один партнёр: Arbihunter.
--
-- Решение владельца от 15.09.2026, и это смена не настройки, а модели.
-- Сервис становится платформой из двух разделов: «Подработка» — смены
-- линейного персонала, «Работа» — постоянные вакансии компаний. Чужие
-- вакансии в разделе «Работа» мы берём у одного партнёра и с официальных
-- карьерных страниц работодателей, а не у агрегаторов.
--
-- Выключаем «Работу в России» (trudvsem), SuperJob и hh.ru. Именно выключаем,
-- а не удаляем: строка источника хранит историю обходов, счётчики и
-- накопленные вакансии, а удаление оборвало бы ссылки у jm_ext_vacancies.
-- Вернуть любой из них — одна правка `enabled` в панели.
--
-- Что произойдёт с их вакансиями. Записи остаются, но перестают обновляться:
-- ingest помечает непришедшие как неактивные при следующем обходе живых
-- источников, и лента их постепенно теряет. Разом ничего не исчезает и в
-- ленте дыры не появится.
--
-- ЧЕСТНОЕ ПРЕДУПРЕЖДЕНИЕ, записанное здесь намеренно. На этих трёх держался
-- основной объём: hh тянул всю Москву, trudvsem — государственный каталог.
-- После выключения поток чужих вакансий падает до каталога Arbihunter (на
-- 15.09 это 303 вакансии) плюс свои. Карьерные страницы объём пока не
-- заменят: коннектор `career.php` читает только разметку schema.org
-- JobPosting, а её нет ни у одного из проверенных работодателей — ни у
-- складских (Самокат, X5, Магнит, ВкусВилл), ни у крупных IT (Сбер, МТС,
-- Яндекс, Ozon, ВТБ, VK, Т-Банк). Подробности и цифры — в
-- docs/источники-вакансий-разбор.md.

update public.jm_ext_sources
   set enabled = false
 where id in ('trudvsem', 'superjob', 'headhunter');

-- Arbihunter — единственный оставшийся партнёр, поэтому убеждаемся, что он
-- включён, а не полагаемся на то, что его никто не трогал.
update public.jm_ext_sources
   set enabled = true
 where id = 'arbihunter';

notify pgrst, 'reload schema';
