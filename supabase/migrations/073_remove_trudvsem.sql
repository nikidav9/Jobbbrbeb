-- «Работа в России» (trudvsem) убирается совсем. Решение владельца от 15.09.2026.
--
-- Миграция 072 этот источник ВЫКЛЮЧАЛА и объясняла, почему не удаляет: строка
-- хранит историю обходов, а удаление «оборвало бы ссылки у jm_ext_vacancies».
-- Оба довода оказались неверны, и это выяснилось при подготовке удаления.
--
-- Первый. Ссылок по внешнему ключу нет вовсе: в jm_ext_vacancies поле
-- source_id объявлено как `text not null` без references (миграция 031), в
-- jm_partner_applications ext_vacancy_id — тоже просто текст (045). Удаление
-- ничего не обрывает и ни на что не каскадирует.
--
-- Второй, и он хуже. Выключение не держалось. infra/local-web-deploy.sh при
-- КАЖДОМ выкате делал upsert этого источника с `enabled = true` — то есть
-- следующий же деплой включал «Работу в России» обратно. Строка из скрипта
-- убрана тем же коммитом, иначе эта миграция откатилась бы сама собой.
--
-- Порядок важен: сначала вакансии, потом источник. Наоборот — и записи
-- остались бы сиротами в ленте навсегда: обходить их стало бы некому, а
-- неактивными их помечает именно обход своего источника.

-- Явные begin/commit: infra/migrate.sh гоняет psql БЕЗ --single-transaction,
-- то есть каждый оператор фиксируется сам по себе. Без обёртки падение на
-- втором delete оставило бы источник без вакансий — состояние, которого не
-- предусмотрено нигде.
begin;

delete from public.jm_ext_vacancies where source_id = 'trudvsem';
delete from public.jm_ext_sources   where id = 'trudvsem';

commit;

-- Отклики и история их статусов (jm_partner_applications и связанные) НЕ
-- трогаются намеренно. Внешнего ключа там нет, записи переживут удаление
-- вакансии, а человек, откликнувшийся через нас, имеет право на свою историю.

notify pgrst, 'reload schema';
