-- Отзыв поручения на автоотклик Юпитера: переключатель в «Профиль → Настройки».
--
-- jupiter_live_enabled_at (106) фиксирует включение. Отдельная отметка нужна,
-- чтобы отличить «ещё не включал» от «включал и выключил» — иначе повторное
-- согласие с документами (jt_jupiter_auto_enable) включило бы автоотклик
-- обратно тем, кто сам его выключил.
alter table jm_users
    add column if not exists jupiter_live_revoked_at timestamptz;
