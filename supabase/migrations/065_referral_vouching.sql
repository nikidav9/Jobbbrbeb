-- Приглашения без денег: вместо выплаты — поручительство.
--
-- Решение владельца: платить за приглашённых пока нечем. Программу из
-- миграции 064 это не отменяет — отменяет только обещание денег, которого мы
-- сдержать не можем. Обещание без суммы читается как обман, а обещание с
-- суммой, которую не выплатят, — хуже, чем отсутствие программы.
--
-- Чем вознаграждаем вместо денег. Тем, что в этом рынке действительно
-- дефицитно и чего у нас в избытке: доверием работодателя. Позвать знакомого
-- значит за него поручиться. Вышел он на первую смену — это записано и видно
-- работодателям на карточке поручителя. Не вышел — тоже записано.
--
-- Почему это работает, а выплата за регистрацию не работала бы:
--   * награда переменная — заранее не знаешь, выйдет твой знакомый или нет;
--   * она накапливается, и чем больше накоплено, тем дороже уходить;
--   * риск обоюдный, поэтому её нельзя нафармить: позвать сто случайных
--     людей значит испортить себе разрыв между «позвал» и «вышли».
-- И главное: она растёт ровно от того, ради чего сервис существует, — от
-- выходов на смены, а не от времени в приложении.
--
-- Имя таблицы jm_referral_rewards оставлено историческим: её читает и пишет
-- только php-proxy под service_role, наружу она не отдаётся ни строкой, и
-- переименование стоило бы рискованной DDL на таблице, которую отсюда не
-- посмотреть, ради одной только опрятности.

-- Итог первой смены приглашённого. До этой миграции записывались только
-- выходы, поэтому 'worked' по умолчанию — правда для всех прежних строк.
alter table public.jm_referral_rewards
  add column if not exists outcome text not null default 'worked';

alter table public.jm_referral_rewards
  drop constraint if exists jm_referral_rewards_outcome_check;
alter table public.jm_referral_rewards
  add constraint jm_referral_rewards_outcome_check
  check (outcome in ('worked', 'no_show'));

-- Денежные поля убираем. Пока они есть, кто-нибудь однажды проставит сумму и
-- решит, что её кто-то выплатит. Схема не должна обещать того, чего нет.
alter table public.jm_referral_rewards drop column if exists amount_rub;
alter table public.jm_referral_rewards drop column if exists paid_at;
alter table public.jm_referral_rewards drop column if exists status;

-- Сколько приведённых этим человеком вышли на первую смену. Денормализация
-- ради одного экрана: карточку кандидата работодатель видит списком, и
-- считать по таблице на каждого значило бы сорок запросов на экран.
-- Пишет это поле только jt_referral_on_outcome в php-proxy, в тот же заход,
-- что заводит строку поручительства.
alter table public.jm_users
  add column if not exists referral_worked integer not null default 0;

-- Пересчёт из журнала. Заодно чинит расхождение, если инкремент когда-нибудь
-- потеряется: миграцию можно прогнать повторно, она идемпотентна.
--
-- Считаем подзапросом на каждого, а НЕ соединением с группировкой по журналу.
-- Соединение было бы внутренним, и человек без единой строки 'worked' в нём
-- просто не участвовал бы — то есть единственный случай, который и надо
-- чинить, счётчик больше нуля при нуле поручительств, пересчёт бы пропустил.
-- coalesce там стоял зря: в результат соединения null не приходит никогда.
update public.jm_users u
   set referral_worked = (
     select count(*) from public.jm_referral_rewards r
      where r.inviter_id = u.id and r.outcome = 'worked')
 where u.referral_worked is distinct from (
     select count(*) from public.jm_referral_rewards r
      where r.inviter_id = u.id and r.outcome = 'worked');

notify pgrst, 'reload schema';
