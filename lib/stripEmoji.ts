/**
 * Эмодзи в интерфейсе не используем (решение владельца 01.10.2026: «нам не
 * нужны никакие смайлики в приложении»). Тексты приходят и с сервера —
 * уведомления, ошибки, — поэтому снимаем их при показе, а не только в коде.
 *
 * Разбор старых уведомлений по первому эмодзи заголовка (routeByTitle) идёт
 * по исходной строке: снимать эмодзи нужно только там, где текст рисуется.
 */
const EMOJI = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{2300}-\u{23FF}\u{FE0F}\u{200D}\u{20E3}]/gu;

export function stripEmoji(text: string): string {
  return text.replace(EMOJI, '').replace(/\s{2,}/g, ' ').trim();
}
