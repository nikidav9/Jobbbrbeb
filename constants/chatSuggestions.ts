import { Vacancy } from '@/constants/types';

// Готовые фразы для чата сразу после отклика: поле ввода пустое, и обе стороны
// молчат, не зная, с чего начать. Нажатие подставляет текст в поле — не
// отправляет, чтобы можно было дописать под себя.

export type ChatSuggestion = {
  id: string;
  /** Короткая надпись на чипе */
  label: string;
  /** Текст, который подставится в поле ввода */
  text: string;
};

/**
 * Первое сообщение директора одобренному кандидату.
 *
 * Раньше на этом месте стоял шаблон «Свяжитесь с кандидатом для уточнения
 * деталей» — и он же уходил кандидату. Обе стороны прочитали «свяжись
 * первым» и стали ждать друг друга: в переписке так и оставалось два
 * системных сообщения и ни одного живого.
 */
export const PERM_APPROVE_SUGGESTIONS: ChatSuggestion[] = [
  { id: 'when', label: 'Когда сможете выйти?', text: 'Здравствуйте! Готовы вас взять. Когда сможете выйти?' },
  { id: 'call', label: 'Созвонимся',           text: 'Давайте созвонимся — наберу вас сегодня.' },
  { id: 'docs', label: 'Оформление',           text: 'Подъезжайте в офис оформляться, возьмите паспорт.' },
  { id: 'exp',  label: 'Какой опыт?',          text: 'Расскажите, где работали раньше?' },
];

export function getChatSuggestions(
  role: 'worker' | 'employer',
  vacancy?: Vacancy | null,
): ChatSuggestion[] {
  // С 17.09.2026 смен нет — только постоянная работа. Прежние фразы про
  // «выход на смену», склад и Лавку уходили IT-работодателю одним нажатием.
  const address = vacancy?.address ?? '';
  const station = vacancy?.metroStation ?? '';

  if (role === 'employer') {
    const out: ChatSuggestion[] = [
      { id: 'thanks', label: 'Спасибо за отклик', text: 'Здравствуйте! Спасибо за отклик на вакансию.' },
      { id: 'exp', label: 'Расскажите об опыте', text: 'Расскажите, пожалуйста, о вашем опыте.' },
      { id: 'call', label: 'Созвонимся?', text: 'Давайте созвонимся — когда вам удобно?' },
      { id: 'interview', label: 'Собеседование', text: 'Приглашаем вас на собеседование. Какое время вам удобно?' },
      { id: 'salary', label: 'Ожидания по зарплате', text: 'Какие у вас ожидания по зарплате?' },
    ];
    if (address || station) {
      const parts = [address ? `Адрес: ${address}.` : '', station ? `Ближайшее метро — ${station}.` : '']
        .filter(Boolean).join(' ');
      out.push({ id: 'address', label: 'Адрес', text: parts });
    }
    return out;
  }

  return [
    { id: 'hello', label: 'Здравствуйте', text: 'Здравствуйте! Меня заинтересовала ваша вакансия.' },
    { id: 'interview', label: 'Когда собеседование?', text: 'Когда можно пройти собеседование?' },
    { id: 'call', label: 'Готов созвониться', text: 'Готов созвониться — во сколько вам удобно?' },
    { id: 'format', label: 'Формат работы', text: 'Подскажите, какой формат работы: офис, гибрид или удалённо?' },
    { id: 'salary', label: 'Зарплата', text: 'Подскажите, пожалуйста, вилку зарплаты.' },
    { id: 'next', label: 'Следующие шаги', text: 'Какие следующие шаги?' },
  ];
}
