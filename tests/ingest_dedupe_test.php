<?php
// Отпечаток вакансии: что считать одной и той же, а что разными.
//
// Зачем проверка. Отпечаток склеивает одинаковые предложения, приехавшие от
// разных партнёров, — иначе лента выглядит спамом. Но он же и ТЕРЯЕТ вакансии,
// если склеивает слишком грубо, а потеря тихая: строка в базе есть, в ленте её
// нет, и понять это можно только счётом.
//
// Так и вышло. METRO не присылает ни адреса, ни метро, отпечаток вырождался в
// «компания + должность» — и 194 вакансии из 294 в ленту не попадали вовсе.
// Двадцать три разных «Продавца-кассира» в разных магазинах были одной
// карточкой. Заодно расходились счётчик в шторке фильтров и сам список:
// сервер считает по отпечаткам, а показывает по ним же, но человек видел
// «Показать 4» и пустой экран.
//
// INGEST_LIBRARY_ONLY гасит точку входа: сети и базы здесь нет.
define('INGEST_LIBRARY_ONLY', true);
require_once __DIR__ . '/../php-proxy/ingest.php';

$failures = [];
function check(string $name, bool $ok): void {
    global $failures;
    if (!$ok) $failures[] = $name;
}

$perm = fn(array $over = []) => array_merge([
    'kind' => 'permanent', 'company' => 'METRO', 'title' => 'Продавец-кассир',
    'address' => null, 'metro_station' => null, 'metro_station_norm' => null,
    'date' => null, 'time_start' => null,
    'url' => 'https://rabota.metro-cc.ru/vacancy/21580',
], $over);

// ── Главное: без места различаем по адресу вакансии ───────────────────────
$a = ing_dedupe_key($perm());
$b = ing_dedupe_key($perm(['url' => 'https://rabota.metro-cc.ru/vacancy/21581']));
check('без адреса и метро разные вакансии не схлопываются', $a !== $b);

// Та же самая вакансия (тот же адрес) остаётся одной — иначе каждый обход
// плодил бы копии.
check('та же вакансия даёт тот же отпечаток', $a === ing_dedupe_key($perm()));

// ── Место есть — отпечаток его и использует, адрес вакансии не примешиваем ──
// Это и стережёт сведение одинаковых смен от РАЗНЫХ партнёров: у них разные
// адреса страниц, и если бы адрес входил в отпечаток всегда, дедуп умер бы.
$withAddr = fn(string $url) => ing_dedupe_key($perm([
    'address' => 'Москва, Дорожная ул., 1', 'url' => $url,
]));
check('при известном адресе партнёры сводятся',
    $withAddr('https://a.example/1') === $withAddr('https://b.example/2'));

$withMetro = fn(string $url) => ing_dedupe_key($perm([
    'metro_station_norm' => 'Тёплый Стан', 'url' => $url,
]));
check('при известном метро партнёры сводятся',
    $withMetro('https://a.example/1') === $withMetro('https://b.example/2'));

// ── Смены не трогаем: у них место есть всегда, и адрес в отпечаток не идёт ──
$shift = fn(string $url) => ing_dedupe_key([
    'kind' => 'shift', 'company' => 'Склад', 'title' => 'Комплектовщик',
    'metro_station_norm' => 'Тёплый Стан', 'date' => '2026-09-20',
    'time_start' => '09:00', 'address' => null, 'url' => $url,
]);
check('смены от разных партнёров по-прежнему сводятся',
    $shift('https://a.example/1') === $shift('https://b.example/2'));

// Смена без места (такой в ленте не бывает — её нечем показать) тоже не должна
// разъезжаться по адресу страницы: правило заведено только для постоянных.
$shiftNoPlace = fn(string $url) => ing_dedupe_key([
    'kind' => 'shift', 'company' => 'Склад', 'title' => 'Комплектовщик',
    'date' => '2026-09-20', 'time_start' => '09:00', 'url' => $url,
]);
check('правило про адрес вакансии не распространяется на смены',
    $shiftNoPlace('https://a.example/1') === $shiftNoPlace('https://b.example/2'));

// ── Прежнее поведение на месте ────────────────────────────────────────────
check('разные должности — разные вакансии',
    ing_dedupe_key($perm(['address' => 'Москва, Дорожная ул., 1']))
    !== ing_dedupe_key($perm(['address' => 'Москва, Дорожная ул., 1', 'title' => 'Кассир'])));
// Мутация «убрать метро из отпечатка» сначала НЕ поймалась: проверка выше
// говорит только, что при одинаковом метро вакансии сводятся, а это верно и
// когда метро в отпечаток не входит вовсе. Нужна пара с РАЗНЫМ метро.
check('разное метро — разные вакансии',
    ing_dedupe_key($perm(['metro_station_norm' => 'Тёплый Стан']))
    !== ing_dedupe_key($perm(['metro_station_norm' => 'Планерная'])));
check('разное метро различает и смены',
    ing_dedupe_key(['kind' => 'shift', 'company' => 'Склад', 'title' => 'Комплектовщик',
        'metro_station_norm' => 'Тёплый Стан', 'date' => '2026-09-20', 'time_start' => '09:00'])
    !== ing_dedupe_key(['kind' => 'shift', 'company' => 'Склад', 'title' => 'Комплектовщик',
        'metro_station_norm' => 'Планерная', 'date' => '2026-09-20', 'time_start' => '09:00']));
// Та же дыра, что и с метро: «сводятся при одинаковой дате» верно и когда
// даты в отпечатке нет. Смена завтра и смена послезавтра — разные смены.
$shiftOn = fn(string $date, string $from) => ing_dedupe_key([
    'kind' => 'shift', 'company' => 'Склад', 'title' => 'Комплектовщик',
    'metro_station_norm' => 'Тёплый Стан', 'date' => $date, 'time_start' => $from,
]);
check('разные дни — разные смены',
    $shiftOn('2026-09-20', '09:00') !== $shiftOn('2026-09-21', '09:00'));
check('разное начало — разные смены',
    $shiftOn('2026-09-20', '09:00') !== $shiftOn('2026-09-20', '18:00'));
check('разные адреса — разные вакансии',
    ing_dedupe_key($perm(['address' => 'Москва, Дорожная ул., 1']))
    !== ing_dedupe_key($perm(['address' => 'Москва, Дорожная ул., 2'])));
check('лишний пробел и регистр в адресе не делают вакансию новой',
    ing_dedupe_key($perm(['address' => 'Москва,  Дорожная  ул., 1']))
    === ing_dedupe_key($perm(['address' => 'москва, Дорожная ул., 1'])));
check('отпечаток длиной 32', strlen($a) === 32);

if ($failures) {
    echo "ingest dedupe: ПРОВАЛЫ\n";
    foreach ($failures as $f) echo "  - $f\n";
    exit(1);
}
echo "ingest dedupe: OK\n";
