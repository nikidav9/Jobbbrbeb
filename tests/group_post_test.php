<?php
// Объявление в группу «ПОДРАБОТКИ»: доставка и её видимость.
//
// Написано по живой жалобе: постоянная вакансия висела в ленте восемнадцать
// часов, а сообщения в группе не было. Разбор показал две причины, и обе
// молчаливые.
//
// Проверка текстовая: dbNotifyAllWorkersNewVacancy живёт внутри обработчика
// запроса, подключить его как библиотеку нельзя.

$db = (string)file_get_contents(__DIR__ . '/../php-proxy/db.php');

$failures = [];
function check(string $name, bool $ok): void
{
    global $failures;
    if (!$ok) $failures[] = $name;
}

// ── Отметка о доставке ────────────────────────────────────────────────────────
// Была одна отметка на всё, и ставилась она ДО отправки: сбой при отправке в
// группу означал, что вакансия помечена разосланной навсегда, а повтор с
// клиента получал already_sent и выходил ни с чем.
check('отметки раздельные: письма и группа',
    str_contains($db, "'eq.bcast:' . \$vacancyId") && str_contains($db, "'eq.gpost:' . \$vacancyId"));
check('отметка группы ставится ПОСЛЕ успеха',
    str_contains($db, "if (\$groupOk && \$vacancyId !== '') {"));
check('ранний выход только когда доставлено и то и другое',
    str_contains($db, 'if ($dmAlreadySent && $groupAlreadySent) {'));
// Личные сообщения по-прежнему столбим заранее: повторная рассылка всем
// работникам хуже неотправленной.
check('письма столбятся заранее', str_contains($db, "if (!\$dmAlreadySent) {"));
check('письма не уходят повторно', str_contains($db, "'skipped' => 'dm_already_sent'"));

// Порядок важен: отметка после отправки, а не до.
$claim = strpos($db, "'key' => 'gpost:' . \$vacancyId");
$send = strpos($db, '$groupOk = tg_send_message(TG_GROUP_CHAT_ID');
check('в коде отправка стоит раньше отметки', $send !== false && $claim !== false && $send < $claim);

// ── Видимость отказа ──────────────────────────────────────────────────────────
// Итог последней публикации писался в jm_settings и не читался нигде: в самом
// коде сказано «иначе выяснять причину будет нечем», а читателя не было.
check('итог публикации записывается', str_contains($db, "'key' => 'last_group_post'"));
check('итог публикации читается', str_contains($db, "['key' => 'eq.last_group_post']"));
// Проверяем не НАЛИЧИЕ слов в файле, а то, что они попадают в строку отчёта.
// Первая версия искала «НЕ доставлен» по всему db.php — и оставалась зелёной,
// когда слова лежали в недостижимой функции, а отчёт говорил «доставлен».
// Поймано мутацией. Та же порода, что была у проверки 503 в seo_infra_test:
// строка есть, а дороги до неё нет.
// Ищем ЦЕЛИКОМ присваивание, а не два слова «НЕ доставлен». Прежняя проверка
// искала слова по всему db.php и оставалась зелёной, когда они лежали в
// недостижимой функции, а отчёт говорил «доставлен». Поймано мутацией.
//
// ПРЕДЕЛ МЕТОДА, чтобы никто не принял эту проверку за большее, чем она есть:
// текстовый поиск не видит ДОСТИЖИМОСТЬ. Если живое присваивание удалить, а
// точную его копию положить в мёртвую функцию, проверка останется зелёной — и
// счёт вхождений тут не помогает, вхождение по-прежнему одно. Проверено, не
// предположено. Случайной такой правки не бывает, а от намеренной текстовый
// тест не спасает вовсе: для этого нужен либо разбор PHP, либо живой прогон.
// Что эта проверка правда держит: смену текста, пропажу присваивания и разрыв
// пути до отчёта (следующая проверка).
//
// Счёт вхождений — против случайного дубля: две копии строки в отчёте значат,
// что кто-то скопировал блок и забыл про первый.
check('недоставленный пост виден в отчёте, и ровно в одном месте',
    substr_count($db, '$groupLine = "📣 Последний пост в группу: {$whenMsk} МСК, <b>НЕ доставлен</b> — "') === 1);
check('доставленный пост тоже виден, и ровно в одном месте',
    substr_count($db, '$groupLine = "📣 Последний пост в группу: {$whenMsk} МСК, доставлен"') === 1);
// И что строка вообще доходит до отчёта, а не собирается вхолостую.
check('строка попадает в отчёт', str_contains($db, "if (\$groupLine !== '') \$lines[] = \$groupLine;"));
check('недоставленный пост поднимает тревогу',
    str_contains($db, "\$groupAlert = 'последний пост в группу"));
check('тревога попадает в список', str_contains($db, "if (\$groupAlert !== '') \$alerts[] = \$groupAlert;"));
check('строка попадает в отчёт', str_contains($db, "if (\$groupLine !== '') \$lines[] = \$groupLine;"));

// Причина отказа приходит из Telegram и уходит в разметку сообщения.
check('причина отказа экранируется', str_contains($db, 'htmlspecialchars(mb_substr($whyText'));

// ── Догоняющее объявление ─────────────────────────────────────────────────────
// Главная причина молчания была не на сервере: объявление посылает приложение
// отдельным запросом уже ПОСЛЕ закрытия экрана, а повторы занимают до полутора
// минут. Свернул человек приложение — запрос не ушёл, и сервер о вакансии даже
// не узнал. Починить это можно только со стороны сервера: пусть догоняет сам.
check('догоняющее задание есть', str_contains($db, 'function jt_announce_missed('));
check('задание доступно как операция', str_contains($db, "case 'cronAnnounceMissed':"));
check('операция только для админа', str_contains($db, "'cronAnnounceMissed',"));
// Искать по всему файлу нельзя: те же строки встречаются в других функциях, и
// проверка проходит даже на сломанном коде. Однажды так и вышло — мутация
// «убрать окно по времени» применилась, а тест остался зелёным, потому что
// нашёл 'created_at' => 'gte.' в чужом задании. Вырезаем тело нужной функции.
function fn_body(string $src, string $name): string
{
    $start = strpos($src, "function {$name}(");
    if ($start === false) return '';
    $end = strpos($src, "\n}\n", $start);
    return $end !== false ? substr($src, $start, $end - $start) : substr($src, $start);
}
$missed = fn_body($db, 'jt_announce_missed');
check('тело догоняющего задания найдено', $missed !== '');

check('берёт обе таблицы вакансий',
    str_contains($missed, "'table' => 'jm_perm_vacancies'") && str_contains($missed, "'table' => 'jm_vacancies'"));
check('берёт только открытые', str_contains($missed, "'status' => 'eq.open',"));

// При первом запуске отметки gpost нет НИ У КОГО — она новая. Без окна по
// времени и без учёта старой отметки задание вывалило бы в группу всю историю.
check('окно по времени есть', str_contains($missed, "'created_at' => 'gte.' . \$cut"));
check('старая отметка тоже считается доставкой',
    str_contains($missed, "'eq.gpost:' . \$id") && str_contains($missed, "'eq.bcast:' . \$id"));
// Пределов должно быть ДВА: перед таблицей и перед каждой вакансией. С одним
// внешним задание внутри одной таблицы объявит сколько угодно.
check('предел проверяется и внутри перебора вакансий',
    substr_count($missed, 'count($announced) >= $limit') >= 2);
check('окно и предел ограничены сверху',
    str_contains($db, 'min(48, (int)($args[0] ?? 6))') && str_contains($db, 'min(20, (int)($args[1] ?? 5))'));

// Отметку ставим только после успешной отправки — иначе повторится та же
// ошибка, из-за которой вакансия терялась навсегда.
$sendAt = strpos($db, 'if (!tg_send_message(TG_GROUP_CHAT_ID, $html, $btn)) continue;');
$markAt = strpos($db, "'key' => 'gpost:' . \$id, 'value' => now_iso()");
check('отметка ставится после отправки', $sendAt !== false && $markAt !== false && $sendAt < $markAt);

// Текст собирается на сервере: догоняющее задание не может позвать клиентский
// код. Данные вводят работодатели и они уходят в разметку Telegram.
check('текст объявления собирается на сервере', str_contains($db, 'function jt_group_html('));
check('данные работодателя экранируются',
    str_contains($db, "htmlspecialchars(\$x, ENT_QUOTES, 'UTF-8')"));
check('без названия или компании не объявляем',
    str_contains($db, "if (\$title === '' || \$company === '') return '';"));

// ── Объявляет тот, кто разместил ──────────────────────────────────────────────
// Вход здесь требовался, а чья вакансия — не проверялось, и разметка поста
// приходила с клиента готовой. Любой зарегистрированный мог отправить в
// открытую группу и пушем каждому работнику произвольный текст со своей
// ссылкой. Обработчик лежит в case, а не в функции, — вырезаем его блок.
function case_body(string $src, string $fn): string
{
    $start = strpos($src, "case '{$fn}': {");
    if ($start === false) return '';
    $end = strpos($src, "\n        case '", $start + 10);
    return $end !== false ? substr($src, $start, $end - $start) : substr($src, $start);
}
$notify = case_body($db, 'dbNotifyAllWorkersNewVacancy');
check('тело рассылки найдено', $notify !== '');

check('вакансию берём из базы', str_contains($notify, '$vacancyRow = sb_single('));
check('чужую вакансию не объявляем',
    str_contains($notify, "(string)(\$vacancyRow['employer_id'] ?? '') !== (string)\$authUid")
    && str_contains($notify, "jt_respond(['error' => 'Это не ваша вакансия'], 403)"));
check('несуществующую вакансию не объявляем',
    str_contains($notify, "jt_respond(['error' => 'Вакансия не найдена'], 404)"));

// Порядок здесь не мелочь. Отметка bcast ставится ЗАРАНЕЕ, до рассылки: если
// проверку права пропустить вперёд неё, посторонний успеет пометить чужую
// вакансию разосланной — и настоящее объявление уже не уйдёт никогда.
$ownerAt = strpos($notify, "jt_respond(['error' => 'Это не ваша вакансия'], 403)");
$claimAt = strpos($notify, "'key' => 'bcast:' . \$vacancyId");
check('право проверяется раньше отметки о рассылке',
    $ownerAt !== false && $claimAt !== false && $ownerAt < $claimAt);

// ── Формат объявления живёт в ОДНОМ месте (задача 16) ─────────────────────────
// Было два: приложение собирало разметку и слало её готовой, сервер собирал
// свою для догоняющего задания. Два вида объявления в одной группе выглядели
// бы как поломка, а разъехались бы они непременно.
check('текст поста собирает сервер',
    str_contains($notify, '$groupHtml = jt_group_html($vacancyRow, $deepKind);'));
check('клиентская разметка группы больше не берётся',
    !str_contains($notify, '$args[4]'));
$notifTs = (string)file_get_contents(__DIR__ . '/../services/notifications.ts');
check('приложение больше не собирает пост для группы',
    !str_contains($notifTs, 'В приложении смены появляются раньше'));
check('место довода сохранено ради номеров остальных',
    str_contains($notifTs, "const groupHtml = '';"));

$wf = (string)file_get_contents(__DIR__ . '/../.github/workflows/announce-missed.yml');
check('задание запускается по расписанию', str_contains($wf, "cron: '7 * * * *'"));
check('задание зовёт нужную операцию', str_contains($wf, 'cronAnnounceMissed'));

if ($failures) {
    echo "group post: ПРОВАЛЫ\n";
    foreach ($failures as $f) echo "  - $f\n";
    exit(1);
}
echo "group post: OK\n";
