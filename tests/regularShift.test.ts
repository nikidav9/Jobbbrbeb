import assert from 'node:assert/strict';
import test from 'node:test';

import { isPartTimeSchedule, isRegularShift } from '../services/regularShift.ts';

// Значения ниже взяты из production как есть: это ровно те строки, что лежат в
// поле schedule у внешних вакансий, с числом строк на 16.09.2026.

test('частичная занятость и совместительство — это подработка', () => {
  assert.ok(isPartTimeSchedule('Продавец', 'Частичная занятость / Совместительство · Не имеет значения'));
  assert.ok(isPartTimeSchedule('Оператор', 'Частичная занятость / Совместительство · Удалённая работа (на дому)'));
});

// В проде это поле всегда приходит парой «Частичная занятость /
// Совместительство», поэтому ветка про совместительство сама по себе не
// проверялась: мутация «убрать её» оставалась зелёной. Другие источники пишут
// его отдельно, значит ветка нужна — и нужна проверка на неё.
test('совместительство само по себе тоже подработка', () => {
  assert.ok(isPartTimeSchedule('Оператор', 'Совместительство'));
  assert.ok(isPartTimeSchedule('Бухгалтер', 'Работа по совместительству'));
});

test('неполный рабочий день — это подработка', () => {
  assert.ok(isPartTimeSchedule('Кассир', 'Неполный рабочий день · Не имеет значения'));
  assert.ok(isPartTimeSchedule('Оператор', 'Неполная дистанционная занятость · Не имеет значения'));
});

test('подработка в названии засчитывается без поля графика', () => {
  assert.ok(isPartTimeSchedule('Кассир выходного дня, подработка', null));
  assert.ok(isPartTimeSchedule('Кладовщик частичная занятость', null));
});

// Ради чего правило переписано. Раньше сюда попадали полные ставки.
test('полный рабочий день подработкой не считается', () => {
  assert.ok(!isPartTimeSchedule('Продавец-кассир', 'Полный рабочий день · Не имеет значения'));
  assert.ok(!isPartTimeSchedule('Инженер', 'Полный день'));
});

test('сменный график — это полная ставка, а не подработка', () => {
  assert.ok(!isPartTimeSchedule('Комплектовщик', 'Сменный график работы · Не имеет значения'));
  assert.ok(!isPartTimeSchedule('Повар', 'Сменный график'));
  assert.ok(!isPartTimeSchedule('Грузчик', 'Сменный'));
});

test('вахта — тем более не подработка', () => {
  assert.ok(!isPartTimeSchedule('Бурильщик', 'Работа вахтовым методом · Не имеет значения'));
});

test('гибкий график сам по себе ни о чём не говорит', () => {
  assert.ok(!isPartTimeSchedule('Курьер', 'Гибкий график'));
});

// Главная причина прежней поломки: правило смотрело в описание, а описание
// почти всегда упоминает график между делом. Тип входа намеренно не принимает
// описание — проверяем, что оно и правда ни на что не влияет.
test('описание на решение не влияет', () => {
  const full = { kind: 'permanent', title: 'Продавец-кассир', schedule: 'Полный рабочий день · Не имеет значения' };
  assert.ok(!isRegularShift(full));
  assert.ok(!isRegularShift({ ...full, ...{ description: 'Возможен гибкий график и сменами по договорённости' } as object }));
});

test('разовая смена сюда не относится', () => {
  assert.ok(!isRegularShift({ kind: 'shift', title: 'Комплектовщик', schedule: 'Частичная занятость' }));
});

test('постоянная вакансия с частичной занятостью — относится', () => {
  assert.ok(isRegularShift({ kind: 'permanent', title: 'Кассир', schedule: 'Неполный рабочий день' }));
});
