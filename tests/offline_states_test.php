<?php
// Обрыв связи не выдаётся за пустоту.
//
// Разница для человека решающая. «Смен нет» он читает как «здесь искать
// нечего» и уходит — молча, и в суточном отчёте это выглядит обычным оттоком.
// «Нет активных заявок» только что откликнувшийся прочитает как «мой отклик
// пропал». «Нет сообщений» ждущий ответа прочитает как «мне не ответили».
// Во всех трёх случаях список просто не принесли.
//
// Механизм для различения уже был: refreshVacancies не трогает список при
// обрыве (остаются данные из кэша) и поднимает backendOffline. Экраны
// работодателя им пользовались, экраны работника — нет.

$failures = [];
function check(string $name, bool $ok): void
{
    global $failures;
    if (!$ok) $failures[] = $name;
}

// ── Признак обрыва поднимается и не врёт ─────────────────────────────────────
$ctx = (string)file_get_contents(__DIR__ . '/../contexts/AppContext.tsx');

// Привязываемся к ТЕЛУ загрузки смен, а не к наличию вызова где-нибудь в
// файле: setBackendOffline(true) стоит в трёх местах, и проверка на наличие
// переживала удаление одного. Поймано мутацией — точнее, поймана была сама
// мутация: она заменяла первое вхождение из трёх и ничего не доказывала.
$rv = (function (string $src): string {
    $start = strpos($src, 'const refreshVacancies = async');
    if ($start === false) return '';
    $end = strpos($src, "\n  };\n", $start);
    return $end !== false ? substr($src, $start, $end - $start) : '';
})($ctx);
check('загрузка смен найдена', $rv !== '');
check('обрыв поднимает признак', str_contains($rv, 'setBackendOffline(true);'));
check('успех признак снимает', str_contains($rv, 'setBackendOffline(false);'));
// Порядок: сначала данные легли, потом снят признак. Иначе признак снимется и
// при неудачной записи.
check('признак снимается после данных',
    strpos($rv, 'setVacancies(data)') !== false
    && strpos($rv, 'setVacancies(data)') < strpos($rv, 'setBackendOffline(false);'));
// Список при обрыве НЕ обнуляется: иначе человек потеряет и кэш, и объяснение.
check('при обрыве список не трогаем',
    !preg_match('~catch[^}]*setVacancies\(\[\]\)~s', $ctx));
check('признак отдаётся экранам', str_contains($ctx, "\n        backendOffline,"));

// ── Три экрана работника различают обрыв и пустоту ───────────────────────────
foreach ([
    'app/(tabs)/feed.tsx'    => 'лента',
    'app/(tabs)/matches.tsx' => 'отклики',
    'app/(tabs)/chats.tsx'   => 'переписки',
] as $file => $what) {
    $src = (string)file_get_contents(__DIR__ . '/../' . $file);
    // Именно из контекста, а не локальной заглушкой. Прежняя версия этой
    // проверки заканчивалась поиском 'backendOffline,' по всему файлу и
    // оставалась зелёной, когда экран объявлял `const backendOffline = false`
    // у себя: разметка-то поле поминает. Поймано мутацией.
    // useApp() в файле зовут не один раз (в ленте есть ещё и маленькие
    // компоненты со своей выборкой), поэтому смотрим ВСЕ деструктуризации и
    // требуем, чтобы признак был хотя бы в одной.
    preg_match_all('~const \{([^}]*)\}\s*=\s*useApp\(\);~', $src, $mm);
    $fromContext = false;
    foreach ($mm[1] ?? [] as $block) {
        if (str_contains($block, 'backendOffline')) { $fromContext = true; break; }
    }
    check("{$what}: признак берётся из контекста", $fromContext);
    check("{$what}: экран не подменяет признак своим",
        !preg_match('~(const|let)\s+backendOffline\s*=~', $src));
    check("{$what}: про связь сказано прямо", str_contains($src, 'Нет связи с сервером'));
    // И сказано ИМЕННО в пустом состоянии, а не где-то ещё в файле.
    check("{$what}: развилка стоит в пустом состоянии",
        (bool)preg_match('~backendOffline[\s\S]{0,400}Нет связи с сервером~', $src));
}

// ── Прежние тексты никуда не делись ──────────────────────────────────────────
// Ветка обрыва добавлена, а не подменила собой полезную подсказку: пустая
// лента с фильтром по-прежнему предлагает фильтр снять.
$feed = (string)file_get_contents(__DIR__ . '/../app/(tabs)/feed.tsx');
check('подсказка про фильтр осталась', str_contains($feed, 'На выбранных станциях смен нет'));
check('подсказка про другой день осталась', str_contains($feed, 'На этот день смен нет'));
check('обычная пустота осталась', str_contains($feed, 'Новых вакансий пока нет'));
$m = (string)file_get_contents(__DIR__ . '/../app/(tabs)/matches.tsx');
check('прежние заголовки откликов остались',
    str_contains($m, 'Нет активных заявок') && str_contains($m, 'Нет отказов'));

// ── У обрыва есть выход ──────────────────────────────────────────────────────
// Тупик хуже ошибки: человеку надо дать действие, а не только диагноз.
check('в ленте можно повторить', str_contains($feed, 'Попробовать снова'));
// Кнопка и её действие рядом, а не просто где-то в файле: onRefresh в ленте
// есть и у обычного обновления, и проверка на его наличие ничего не значила.
check('кнопка повтора зовёт обновление',
    (bool)preg_match('~onPress=\{onRefresh\}[\s\S]{0,200}Попробовать снова~', $feed));

if ($failures) {
    echo "offline states: ПРОВАЛЫ\n";
    foreach ($failures as $f) echo "  - $f\n";
    exit(1);
}
echo "offline states: OK\n";
