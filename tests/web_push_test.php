<?php
// Доставка уведомления тому, у кого нет ни телеграма, ни приложения.
//
// Такой человек существует: мини-апп открывается в браузере, и подписка из
// браузера — единственный способ до него достучаться. До этой проверки он
// получал рассылку о НОВОЙ ВАКАНСИИ и не получал ничего о своих собственных
// событиях: ни о мэтче, ни о сообщении, ни об итоге смены. Событие писалось в
// колокольчик и там и оставалось, пока человек сам не зайдёт.
//
// Проверяем не «функция существует», а каждое звено цепочки по отдельности:
// цепочка рвётся тихо — отправка веб-пуша целиком под catch.

$failures = [];
function check(string $name, bool $ok): void
{
    global $failures;
    if (!$ok) $failures[] = $name;
}

function fn_body(string $src, string $name): string
{
    $start = strpos($src, "function {$name}(");
    if ($start === false) return '';
    $end = strpos($src, "\n}\n", $start);
    return $end !== false ? substr($src, $start, $end - $start) : substr($src, $start);
}

$db = (string)file_get_contents(__DIR__ . '/../php-proxy/db.php');

// ── Полное уведомление доходит и до браузера ─────────────────────────────────
$full = fn_body($db, 'notify_user');
check('полное уведомление найдено', $full !== '');
check('веб-пуш подключён к личным уведомлениям',
    str_contains($full, 'web_push_to([$userId => true]'));
// ЗАПАСНОЙ путь, а не добавочный. У кого есть телеграм или приложение, тот уже
// извещён, и второй звонок о том же — то самое «просто так», от которого
// выключают уведомления целиком.
check('веб-пуш только когда других путей нет',
    str_contains($full, "if (empty(\$u['telegram_id']) && empty(\$u['push_token'])) {"));
// Порядок: сначала телеграм и Expo, браузер последним. Иначе «запасной» путь
// сработал бы раньше основного.
$tgAt = strpos($full, 'tg_send_message(');
$webAt = strpos($full, 'web_push_to(');
check('браузер идёт после основных путей',
    $tgAt !== false && $webAt !== false && $tgAt < $webAt);

// ── Тихое остаётся тихим ─────────────────────────────────────────────────────
// Отказ по смене ходит через notify_bell намеренно: отказов много, и пуш по
// каждому кончается выключенными уведомлениями. Веб-пуш — такой же пуш.
$bell = fn_body($db, 'notify_bell');
check('колокольчик найден', $bell !== '');
check('колокольчик не шлёт веб-пуш', !str_contains($bell, 'web_push_to('));

// ── Рассылку о новой вакансии не сломали ─────────────────────────────────────
// Веб-пуш там был и до правки; если он оттуда пропадёт, четверо перестанут
// узнавать о сменах вовсе.
check('рассылка по-прежнему шлёт веб-пуш',
    str_contains($db, '$webOk = web_push_to($webIds, $title, $body, $dataType);'));
check('оба пути ведут в одну функцию', substr_count($db, 'web_push_to(') >= 3);

// ── Подписки спрашиваются точечно ────────────────────────────────────────────
// Раньше выборка шла по всей таблице и отсеивалась в PHP: на одну рассылку в
// сутки это ничего не стоило, теперь сюда заходит каждое личное уведомление.
$wp = fn_body($db, 'web_push_to');
check('отправка найдена', $wp !== '');
check('подписки берутся по нужным людям',
    str_contains($wp, "['user_id' => 'in.(' . sb_in_list(\$chunk) . ')'],"));
check('таблица целиком не выбирается',
    !str_contains($wp, "sb_select('jm_web_push_subscriptions', [],"));
// Идентификаторы уходят в адрес запроса. Длинный список сломал бы его целиком,
// а поломка здесь тихая — вся отправка под catch.
check('список режется на порции', str_contains($wp, 'array_chunk(array_keys($userIds), 100)'));
// Значения берутся в кавычки тем же sb_in_list, что и везде: id приходит с
// клиента при регистрации, и запятая внутри разорвала бы список.
check('значения экранируются', str_contains($wp, 'sb_in_list('));

// ── Ключи подписи здесь не лежат ─────────────────────────────────────────────
// VAPID живёт в дашборде, php-proxy ходит к нему по HTTP. Второй экземпляр
// ключей — лишний способ их потерять, а репозиторий публичный.
check('ключи подписи не в прокси',
    !preg_match('~VAPID|vapidDetails~i', $wp));
check('отправка идёт через дашборд', str_contains($wp, "DASHBOARD_URL . '/api/webpush/send'"));
check('запрос подписан секретом приложения',
    str_contains($wp, "'x-app-secret: ' . \$appSecret"));

if ($failures) {
    echo "web push: ПРОВАЛЫ\n";
    foreach ($failures as $f) echo "  - $f\n";
    exit(1);
}
echo "web push: OK\n";
