<?php
// Плашка «как отвечает работодатель» доходит до места, где принимают решение.
//
// Решение в этом продукте принимается СВАЙПОМ: одно движение, ноль раздумий.
// Плашка при этом показывалась только в подробностях и на странице вакансии —
// то есть тем единицам, кто дотапал. Предупреждать о молчуне после того, как
// отклик ушёл, поздно: отклик без ответа человек читает как «сервис не
// работает» и уходит.
//
// 17.09 раздел подработки удалён целиком, вместе с карточкой смены. Проверка
// переехала на карточку постоянной вакансии — теперь свайпают только её.

$failures = [];
function check(string $name, bool $ok): void
{
    global $failures;
    if (!$ok) $failures[] = $name;
}

$feed = (string)file_get_contents(__DIR__ . '/../app/(tabs)/feed.tsx');

// ── Плашка на карточке свайпа ────────────────────────────────────────────────
check('плашка подключена', str_contains($feed, "import { ReplyBadge } from '@/components/feature/ReplyBadge';"));
check('плашка на карточке', str_contains($feed, '<ReplyBadge stats={responsivenessMap[v.employerId]} />'));
// Смотрим ВСЕ деструктуризации useApp, а не одну строку целиком: в ленте
// useApp зовут несколько раз, и любая новая строка рядом ломала бы проверку
// на ровном месте. Так и вышло, когда рядом добавился backendOffline.
preg_match_all('~const \{([^}]*)\}\s*=\s*useApp\(\);~', $feed, $uses);
$mapFromContext = false;
foreach ($uses[1] ?? [] as $block) {
    if (str_contains($block, 'responsivenessMap')) { $mapFromContext = true; break; }
}
check('карта берётся из контекста, а не запросом на карточку',
    $mapFromContext && !preg_match('~dbResponsivenessMap\(~', $feed));

// ── Место: до разделителя ────────────────────────────────────────────────────
// cardSummary стоит flexShrink, поэтому лишняя высота съедает описание, а не
// выталкивает ссылку «Читать полностью» за край. Уехавшую ссылку без прокрутки
// внутри карточки уже ничем не достать — прокрутки там нет намеренно.
//
// Порядок ищем ВНУТРИ тела карточки, а не по всему файлу. Первая версия этой
// проверки искала разделитель начиная от плашки — и находила следующий
// разделитель где-то дальше в файле. Плашку можно было переставить за
// разделитель, и проверка оставалась зелёной: ровно та видимость, которая
// хуже отсутствия проверки. Поймано мутацией.
//
// 17.09 тело карточки перестало быть Pressable: вся вакансия теперь внутри, и
// нажатие на всю площадь уводило со страницы при попытке прокрутить. Конец
// тела ищем по закрытию жеста, а «Читать полностью» больше нет — за ней теперь
// раздел «Описание вакансии».
$bodyStart = strpos($feed, 'style={styles.cardBody}');
$bodyEnd = $bodyStart !== false ? strpos($feed, '</GestureDetector>', $bodyStart) : false;
$body = ($bodyStart !== false && $bodyEnd !== false)
    ? substr($feed, $bodyStart, $bodyEnd - $bodyStart) : '';
check('тело карточки свайпа найдено', $body !== '');

$badgeAt = strpos($body, '<ReplyBadge stats={responsivenessMap');
$dividerAt = strpos($body, '<View style={styles.cardDivider} />');
$descAt = strpos($body, 'Описание вакансии');
$chipsAt = strpos($body, '<View style={styles.chipsRow}>');
check('плашка внутри тела карточки', $badgeAt !== false);
check('плашка стоит после чипов',
    $badgeAt !== false && $chipsAt !== false && $chipsAt < $badgeAt);
// Перенесено из #193, чтобы этот PR не ждал его мержа: редизайн карточки в
// main убрал разделитель из тела, и проверка требовала не порядка, а наличия
// разделителя. Смысл — «предупредить до решения» — держат соседние проверки:
// после чипов и ДО описания. Станет пустой строкой, когда #193 смержится.
check('плашка стоит до разделителя, если он есть',
    $badgeAt !== false && ($dividerAt === false || $badgeAt < $dividerAt));
check('плашка стоит до описания вакансии',
    $badgeAt !== false && $descAt !== false && $badgeAt < $descAt);

// ── Карточка никуда не ведёт ────────────────────────────────────────────────
// Это была жалоба владельца: попытка прокрутить открывала страницу вакансии.
// Причина — кнопка на всей площади карточки: палец, ушедший вниз, отменял
// свайп, список начинал крутить, а нажатие на отпускании срабатывало.
check('тело карточки не кнопка', !str_contains($body, 'accessibilityRole="button"'));
check('из карточки нет перехода на страницу вакансии',
    !str_contains($body, 'perm-vacancy-detail'));
// Вся вакансия должна быть в карточке, иначе уводить всё-таки придётся.
check('в карточке есть расположение', str_contains($body, 'Расположение'));
check('в карточке есть описание', $descAt !== false);
// 17.09 описание перестало ужиматься — его теперь листают. Проверяем новый
// механизм: карточка растёт по содержимому, а список вокруг неё прокручивает.
check('карточка растёт по содержимому, а не режется по экрану',
    str_contains($feed, 'cardAnimated: { flexGrow: 1') && !str_contains($feed, 'cardAnimated: { flex: 1'));
check('описание не режется по числу строк',
    !preg_match('~<Text style=\{pS\.desc\}\s+numberOfLines~', $feed));
check('карточку есть чем листать', str_contains($feed, 'ref={cardScrollRef}'));
// Прокрутка и свайп делят одну площадь, и разнимает их failOffsetY: палец,
// ушедший вниз, отменяет горизонтальный жест. Без него карточка будет
// улетать от попытки полистать — ровно то, на чём горели в прошлый раз.
$deck = (string)file_get_contents(__DIR__ . '/../hooks/useSwipeDeck.ts');
check('вертикаль отменяет свайп', str_contains($deck, '.failOffsetY([-20, 20])'));

// ── Плашка молчит, когда сказать нечего ──────────────────────────────────────
$badge = (string)file_get_contents(__DIR__ . '/../components/feature/ReplyBadge.tsx');
check('по одной переписке вывода не делаем',
    str_contains($badge, 'if (!stats || stats.chats < 2) return null;'));

// ── Старое место не потеряно ─────────────────────────────────────────────────
// Плашка добавлена к свайпу, а не переехала: в подробностях она тоже нужна.
$perm = (string)file_get_contents(__DIR__ . '/../app/perm-vacancy-detail.tsx');
check('на странице вакансии плашка осталась', str_contains($perm, '<ReplyBadge'));

if ($failures) {
    echo "reply badge: ПРОВАЛЫ\n";
    foreach ($failures as $f) echo "  - $f\n";
    exit(1);
}
echo "reply badge: OK\n";
