// Что считается регулярной подработкой.
//
// Раздел «Подработка → Регулярная» — для тех, кто ищет ЧАСТИЧНУЮ занятость:
// несколько смен в неделю рядом с учёбой или основной работой. Это не «любой
// необычный график».
//
// Прежнее правило ловило по словам «сменн|подработ|частичн|неполн|гибк|вахт|
// совместитель» и смотрело в том числе ОПИСАНИЕ вакансии. Обе части оказались
// неверными, и владелец увидел в разделе полноценные ставки.
//
// Первое. Сменный график и вахта — это полный рабочий день, просто не с девяти
// до шести. По базе таких 675 сменных и 63 вахтовых: человеку, который ищет
// подработку, они не подходят. Гибкий график тоже не признак — он бывает и у
// полной занятости.
//
// Второе, и оно важнее. Описание смотреть нельзя. Оно длинное и почти всегда
// упоминает график между делом: «возможен гибкий график», «сменами по
// договорённости». Пока описаний в базе почти не было, это сходило с рук —
// а после того как сборщик начал добирать их со страниц вакансий, в раздел
// хлынули полные ставки. Смотрим только должность и поле графика.
//
// Посчитано на всех 7997 постоянных вакансиях прода: прежнее правило давало
// 2085 карточек, новое — 1230. Ушли ровно сменные, вахтовые и гибкие.
// Классы букв заданы явно ([а-яё]), а не через \w: в JavaScript \w — это
// [A-Za-z0-9_] и кириллицу НЕ покрывает. Первую версию правила я замерил
// питоном, где \w покрывает, и в тестах она развалилась ровно на русских
// словах. Мерить надо тем же движком, который потом исполняет.
const PART_TIME = /частичн[а-яё]*(?:[\s,/-]+[а-яё]+){0,3}[\s,/-]*занятост|неполн[а-яё]*(?:[\s,/-]+[а-яё]+){0,3}[\s,/-]*(?:занятост|рабоч[а-яё]*\s+день)|совместительств|подработ/i;

/**
 * Поля вакансии, по которым решаем. Намеренно узкий тип: так видно, что
 * описание сюда не передаётся, и это не забудется при следующей правке.
 */
export type RegularShiftInput = {
  kind?: string;
  title?: string | null;
  schedule?: string | null;
};

export function isPartTimeSchedule(title?: string | null, schedule?: string | null): boolean {
  return PART_TIME.test(`${title ?? ''} ${schedule ?? ''}`);
}

export function isRegularShift(v: RegularShiftInput): boolean {
  return v.kind === 'permanent' && isPartTimeSchedule(v.title, v.schedule);
}
