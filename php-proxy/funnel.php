<?php
// Разрыв воронки: отклик подан — ответил ли кто-нибудь.
//
// Суточный отчёт считал, СКОЛЬКО откликов подали, и молчал о том, что с ними
// стало. А это самый опасный разрыв во всей воронке: отклик без ответа — это
// обещание, которое сервис не сдержал. Switch и Jobr считали матчи, а не
// результат, и исчезли; человек с десятью матчами и без единой смены уходит
// навсегда, и уходит молча — в отчёте это выглядит как рост.
//
// Окно намеренно ВЧЕРАШНЕЕ, а не последние сутки. Метрика называется «доля
// откликов, получивших ответ в течение суток», значит у отклика должны быть
// эти сутки. Если считать по последним 24 часам, туда попадёт отклик,
// поданный пять минут назад, и он честно испортит долю — работодатель ещё
// спит.
//
// Здесь только чистые функции: ни базы, ни сети. Метрику нельзя проверить на
// живых данных отсюда, а метрика, которая молча показывает ноль, хуже
// отсутствующей: она соврёт владельцу, что никто не отвечает, когда на деле
// сломан фильтр.

/**
 * Вчерашние сутки: [from, to). У откликов из этого окна был полный день.
 *
 * Границы в том же виде, что понимает PostgREST и в каком отчёт уже считает
 * всё остальное.
 */
function funnel_window(int $now): array
{
    return [
        'from' => gmdate('Y-m-d\TH:i:s\Z', $now - 48 * 3600),
        'to'   => gmdate('Y-m-d\TH:i:s\Z', $now - 24 * 3600),
    ];
}

/**
 * Доля ответивших, 0..1. null — откликов не было, и доли не существует.
 *
 * Ноль и «не было» — разные вещи. Ноль значит «спрашивали и не ответили»,
 * это тревога. «Не было» значит, что мерить нечего, и рисовать там 0% —
 * вранье в ту же сторону, что и молча сломанный фильтр.
 */
function funnel_answer_rate(int $asked, int $answered): ?float
{
    if ($asked <= 0) return null;
    // Ответов больше, чем откликов, быть не может. Если пришло такое — врёт
    // запрос, и показывать 130% нельзя: доверие к отчёту дороже этой строки.
    if ($answered > $asked) $answered = $asked;
    if ($answered < 0) $answered = 0;
    return $answered / $asked;
}

/** Строка в отчёт. Без выдуманных чисел, когда мерить нечего. */
function funnel_line(int $asked, int $answered): string
{
    $rate = funnel_answer_rate($asked, $answered);
    if ($rate === null) return '↩️ Ответы на вчерашние отклики: откликов не было';
    $pct = (int)round($rate * 100);
    return "↩️ Ответы на вчерашние отклики: <b>{$answered}</b> из <b>{$asked}</b> ({$pct}%)";
}

/**
 * Тревога. Пусто — тревожиться не о чем.
 *
 * Порог — половина, и не ниже пяти откликов. Половина потому, что отклик без
 * ответа хуже отказа: отказ человек переживёт и откликнется снова, а молчание
 * он читает как «сервис не работает». Пять — чтобы один неотвеченный отклик из
 * двух не поднимал тревогу каждую ночь: на таких числах это шум, а тревога,
 * которая звенит постоянно, перестаёт быть тревогой.
 */
function funnel_alert(int $asked, int $answered): string
{
    $rate = funnel_answer_rate($asked, $answered);
    if ($rate === null || $asked < 5 || $rate >= 0.5) return '';
    $pct = (int)round($rate * 100);
    return "на вчерашние отклики ответили только {$answered} из {$asked} ({$pct}%)";
}
