<?php
// Одно правило на два входа: какой идентификатор вакансии годится для адреса.
//
// Отдельный файл, потому что правило нужно и странице, и карте сайта, и разойтись
// им нельзя: карта опубликует адрес, который страница не откроет, и робот получит
// битую ссылку из нашей же карты.
//
// Причина ограничения. Идентификатор попадает в путь (/v/<id>), а nginx
// раскодирует проценты ДО того, как сопоставит путь с location. Поэтому «/» и
// пробел, закодированные в карте как %2F и %20, при заходе снова станут собой и
// не совпадут с правилом. Такие адреса мы просто не публикуем.

if (!function_exists('vacancy_id_is_url_safe')) {
    function vacancy_id_is_url_safe(string $id): bool
    {
        return $id !== ''
            && strlen($id) <= 128
            && (bool)preg_match('/^[A-Za-z0-9._~-]+$/', $id);
    }
}
