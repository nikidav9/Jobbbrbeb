// Четыре вида работ, которые выбирает работодатель в самом JobToo.
const JOB_SECTION_BY_WORK_TYPE = [
    'stocker'          => 'warehouse',
    'picker'           => 'warehouse',
    'shift_supervisor' => 'warehouse',
    'cook'             => 'food',
];

/**
 * Раздел вакансии. Сначала название — оно точнее вида работ, который приёмник
 * сам же выводил из названия грубее; вид работ — запасной путь для своих
 * вакансий, у которых название и есть подпись вида.
 */
function job_section(string $title, ?string $workType = null): string
{
    $t = str_replace('ё', 'е', mb_strtolower(trim($title), 'UTF-8'));
    if ($t !== '') {
        foreach (JOB_SECTION_RULES as [$section, $re]) {
            if (preg_match($re, $t)) return $section;
        }
    }
    $wt = strtolower(trim((string)$workType));
    return JOB_SECTION_BY_WORK_TYPE[$wt] ?? 'other';
}
