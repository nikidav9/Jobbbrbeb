<?php
// Здоровье источников партнёрских вакансий.
//
// Отдельный файл, а не кусок db.php, по той же причине, по какой отдельно
// живут partner_core.php и vacancy_url.php: db.php — обработчик запроса, его
// нельзя подключить, не выполнив. Здесь только чистые функции, и их можно
// проверить на выдуманных данных, не поднимая базу.

/** Возраст молчания человеческими словами: «3 дня», «5 часов». */
function ext_source_age(int $seconds): string
{
    if ($seconds >= 86400) {
        $d = (int)floor($seconds / 86400);
        $n10 = $d % 10; $n100 = $d % 100;
        $word = ($n10 === 1 && $n100 !== 11) ? 'день'
            : (($n10 >= 2 && $n10 <= 4 && ($n100 < 12 || $n100 > 14)) ? 'дня' : 'дней');
        return "{$d} {$word}";
    }
    $h = max(1, (int)floor($seconds / 3600));
    $n10 = $h % 10; $n100 = $h % 100;
    $word = ($n10 === 1 && $n100 !== 11) ? 'час'
        : (($n10 >= 2 && $n10 <= 4 && ($n100 < 12 || $n100 > 14)) ? 'часа' : 'часов');
    return "{$h} {$word}";
}

/**
 * Здоровье источников вакансий: молчание по каждому и перекос в один.
 *
 * Раньше отчёт брал максимум last_success_at по всем источникам сразу и
 * тревожился, только если молчали все. Одного живого источника хватало, чтобы
 * скрыть смерть остальных, — а это ровно тот случай, ради которого тревога и
 * заводилась: источник отвалился, вакансии стареют, никто не заметил.
 *
 * Порог молчания у каждого свой: источник с опросом раз в час обязан
 * отчитаться сегодня, источник раз в двенадцать — нет. Берём четыре
 * пропущенных цикла, но не меньше суток: ниже суток тревога начнёт
 * срабатывать на обычной ночной паузе и её перестанут читать.
 *
 * Функция ничего не знает про базу: это позволяет проверить её на выдуманных
 * данных, чего не сделаешь с обработчиком.
 *
 * $sources    — включённые источники (id, name, period_min, last_success_at);
 * $liveCounts — сколько живых вакансий числится за источником, ключ — id.
 */
function ext_source_health(array $sources, array $liveCounts, int $now): array
{
    $totalLive = 0;
    foreach ($sources as $s) {
        $totalLive += (int)($liveCounts[(string)($s['id'] ?? '')] ?? 0);
    }

    $alerts = [];
    $parts = [];
    $topShare = 0.0;

    foreach ($sources as $s) {
        $id = (string)($s['id'] ?? '');
        $name = trim((string)($s['name'] ?? '')) !== '' ? trim((string)($s['name'] ?? '')) : $id;
        // Строка уходит в Телеграм разметкой, а название источника заводит
        // администратор. Угловая скобка в названии уронила бы разбор, и отчёт
        // не пришёл бы вовсе — молча, ровно в тот день, когда он нужен.
        $name = htmlspecialchars($name, ENT_QUOTES, 'UTF-8');
        $live = (int)($liveCounts[$id] ?? 0);
        $share = $totalLive > 0 ? $live / $totalLive : 0.0;
        if ($share > $topShare) $topShare = $share;

        $part = $totalLive > 0
            ? sprintf('%s %d (%d%%)', $name, $live, (int)round($share * 100))
            : sprintf('%s %d', $name, $live);

        $period = (int)($s['period_min'] ?? 0);
        $limit = max(86400, $period * 60 * 4);
        $ts = !empty($s['last_success_at']) ? strtotime((string)$s['last_success_at']) : false;

        if ($ts === false) {
            $alerts[] = "источник «{$name}» ни разу не отработал";
            $part .= ' — ни разу не отработал';
        } elseif ($now - $ts > $limit) {
            $age = ext_source_age($now - $ts);
            $alerts[] = "источник «{$name}» молчит {$age}";
            $part .= " — молчит {$age}";
        }
        $parts[] = $part;
    }

    if (!$sources) $alerts[] = 'включённых источников вакансий нет';

    // Перекос считаем только когда источников больше одного: при единственном
    // источнике доля всегда сто процентов, и ежедневная тревога об этом ничего
    // не сообщает — её перестают читать заодно со всеми остальными. Сам факт
    // виден в строке отчёта, и это честнее постоянного крика.
    if (count($sources) > 1 && $totalLive > 0 && $topShare >= 0.8) {
        $alerts[] = sprintf('на один источник приходится %d%% живых вакансий',
            (int)round($topShare * 100));
    }

    return [
        'line' => '🔗 Источники вакансий: ' . ($parts ? implode(', ', $parts) : 'ни одного включённого'),
        'alerts' => $alerts,
        'top_share' => $topShare,
        'total_live' => $totalLive,
    ];
}
