<?php
// Версия приложения в запросе — заголовок X-App-Version (с 1.0.0, 03.10.2026).
// Зачем: чтобы позже сервер мог отказать слишком старой сборке понятным
// «обновите приложение», а не странной ошибкой. Раньше клиент версию не слал,
// и такую возможность в уже выпущенное приложение добавить было нельзя.
//
// Нет заголовка — клиент старше 1.0.0 (сборка 1.4.0) либо не приложение
// (дашборд, бот): его не трогаем. Мусор в заголовке — тоже не трогаем.

/** Минимальная версия приложения, которую сервер ещё принимает. */
const JT_MIN_APP_VERSION = '1.0.0';

/** Версия из заголовка в виде X.Y.Z или null, если там не версия. */
function jt_app_version(?string $header): ?string
{
    $v = trim((string)$header);
    return preg_match('~^\d{1,4}\.\d{1,4}\.\d{1,4}$~', $v) === 1 ? $v : null;
}

/** Слишком ли стара сборка. Неизвестная версия — не старая. */
function jt_app_version_too_old(?string $header, string $min = JT_MIN_APP_VERSION): bool
{
    $v = jt_app_version($header);
    return $v !== null && version_compare($v, $min, '<');
}
