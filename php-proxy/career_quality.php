/**
 * Разделы карьерного сайта, которые выглядят как ссылка на вакансию, но
 * вакансией не являются. Сравнение — с началом заголовка.
 */
const CQ_SECTIONS = [
    'кадровый резерв', 'контакты', 'школьникам', 'абитуриент', 'студентам',
    'выпускникам', 'корпоративный университет', 'написать нам', 'руководителям',
