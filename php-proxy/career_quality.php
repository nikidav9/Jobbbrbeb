/**
 * Хвосты, которые сайты приклеивают к должности: деньги, «з/п по
 * договоренности», занятость, опыт, дата публикации. Режем с конца, по
 * очереди, пока что-то режется.
 */
const CQ_TAILS = [
    // «78 300 ₽», «от 446 877 ₽ до вычета налогов 18.05.2026»
    '~\s+(?:от\s+|до\s+)?\d[\d\s\x{00A0}\x{202F}]*(?:[.,]\d+)?\s*(?:₽|руб\.?)(?:\s.*)?$~u',
    '~\s+з/п(?:\s.*)?$~u',
    '~\s+(?:полная|частичная|проектная|сменная)\s+занятость(?:\s.*)?$~ui',
    '~\s+\d{2}\.\d{2}\.\d{4}$~u',
];

/** Заголовок без приклеенных хвостов и лишних пробелов. */
function cq_clean_title(string $title): string
{
    $t = trim(preg_replace('/\s+/u', ' ', $title) ?? '');
    for ($i = 0; $i < 4; $i++) {
        $before = $t;
        foreach (CQ_TAILS as $re) $t = trim(preg_replace($re, '', $t) ?? $t);
        if ($t === $before) break;
    }
    return $t;
}

/** Причина, по которой заголовок не вакансия, или null — если вакансия. */
function cq_title_problem(string $title): ?string
{
    $t = cq_clean_title($title);
    if (!preg_match('/\p{L}/u', $t)) return 'в заголовке нет букв';
    if (mb_strlen($t) < 3) return 'заголовок короче трёх знаков';
    $lower = mb_strtolower(trim($t, " \t\"'«»().,:;-"));
    if (in_array($lower, CQ_PLACES, true)) return 'заголовок — название места';
    foreach (CQ_SECTIONS as $s) {
        if (str_starts_with($lower, $s)) return 'заголовок — раздел сайта';
    }
    return null;
}

/**
 * Ссылка ведёт не на вакансию, а на фильтр или служебную страницу:
 * «/career/vacancies/city-6590» у Контура, подписка, рекомендация друга.
 */
function cq_url_problem(string $url): ?string
{
    // Смотрим последний сегмент пути целиком, а не кусок: слаг настоящей
    // вакансии вполне может начинаться с «city-manager» или «contact-center».
    $path = strtolower(rtrim((string)(parse_url($url, PHP_URL_PATH) ?: ''), '/'));
    $last = (string)substr($path, (int)strrpos($path, '/') + 1);
    $last = (string)preg_replace('~\.html?$~', '', $last);
    if (preg_match('~^(?:city|cities|region|regions|town|location|locations)(?:[-_]\d+)?$~', $last)) {
        return 'ссылка на фильтр по городу';
    }
    if (in_array($last, ['subscribe', 'subscription', 'recommend', 'referral', 'feedback',
            'contact', 'contacts', 'reserve', 'faq'], true)) {
        return 'ссылка на служебную страницу';
    }
    return null;
}

/**
 * Прогнать выдачу одной порции через правила.
 *
 * Возвращает ['kept' => годные (с очищенным заголовком), 'rejected' =>
 * [['title', 'url', 'why'], …]]. Годная строка отличается от входной только
 * заголовком: остальное — дело разборщика.
 */
function cf_quality_filter(array $items): array
{
    $kept = [];
    $rejected = [];
    foreach ($items as $it) {
        if (!is_array($it)) continue;
        $title = (string)($it['title'] ?? '');
        $url = (string)($it['url'] ?? '');
        $why = cq_title_problem($title) ?? ($url !== '' ? cq_url_problem($url) : null);
        if ($why !== null) {
            $rejected[] = ['title' => $title, 'url' => $url, 'why' => $why];
            continue;
        }
        $it['title'] = cq_clean_title($title);
        $kept[] = $it;
    }
    return ['kept' => $kept, 'rejected' => $rejected];
}

/**
 * Выдачу адреса целиком не принимаем, если настоящих вакансий на первой
 * порции меньше трёх и при этом (а) не пришло вообще ничего или (б) мусора
 * больше, чем ничего, — то есть было что отсеивать. Это признак перевёрстки
 * сайта: у cofinder так молча ломается каждый седьмой парсер («Parser returned
 * 0 vacancies»). Непринятый адрес идёт как недоступный: его прежние вакансии
 * не гасятся на этом круге, а в журнале видна причина.
 *
 * Честные «две вакансии» (пришло 2, обе годные) проходят: маленькая компания
 * не должна выпадать из ленты за то, что она маленькая.
 */
function cf_quality_rejects(int $raw, int $kept): bool
{
    return $kept < 3 && ($raw === 0 || $kept < $raw);
}
