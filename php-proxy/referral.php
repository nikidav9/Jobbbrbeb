<?php
// Реферальная программа: кто кого привёл и чем это для него обернулось.
//
// Пункт 6 плана развития. Склад — среда с плотными связями: люди зовут
// знакомых на смены и без нас, программа лишь делает это видимым и
// чего-то стоящим для позвавшего.
//
// ГЛАВНОЕ ПРАВИЛО, и оно не обсуждается. Вознаграждение привязано к ИТОГУ
// ПЕРВОЙ СМЕНЫ приглашённого, а не к отклику и не к регистрации. Это прямой
// урок Jobr из разбора конкурентов: там платили за каждый свайп вправо, к
// партнёрам полетели пустые отклики, партнёры отключили фиды — и продукта не
// стало. Считать отклики значит считать количество, а нам нужно качество.
//
// Денег в этой программе нет — решение владельца, платить пока нечем.
// Вознаграждение — поручительство: позвал знакомого, тот вышел на смену, и
// это видно работодателям на карточке поручителя. Не вышел — тоже записано.
// Поэтому здесь записываются ОБА итога: без второго первый ничего не стоит,
// его можно было бы нафармить, позвав сто случайных людей.
//
// Про личные данные. Обычная кнопка «поделиться вакансией» остаётся
// обезличенной: в её ссылке нет и не будет user_id — так решено раньше, и
// это решение мы не трогаем. Приглашение — отдельное действие: человек
// осознанно зовёт знакомого своим кодом и знает, что мы свяжем их двоих.
// Код при этом случайный и из user_id не выводится: попав к третьему лицу,
// он не расскажет о владельце ничего.
//
// Здесь только чистые функции: ни базы, ни сети. Решение «записывать или
// нет» должно проверяться на выдуманных данных — на живой базе такое не
// проверишь, а ошибиться тут значит либо потерять человеку заслуженное, либо
// записать ему чужое.

// Без похожих знаков: код читают вслух и набирают руками, а «0» и «O»
// в этот момент неразличимы.
const REF_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const REF_CODE_LEN = 8;

/** Новый код приглашения. Случайный, из user_id не выводится. */
function ref_code_new(): string
{
    $code = '';
    $max = strlen(REF_ALPHABET) - 1;
    for ($i = 0; $i < REF_CODE_LEN; $i++) {
        $code .= REF_ALPHABET[random_int(0, $max)];
    }
    return $code;
}

/** Годен ли код по виду. Регистр приводим: человек наберёт как придётся. */
function ref_code_normalize(string $raw): ?string
{
    $code = strtoupper(trim($raw));
    if (strlen($code) !== REF_CODE_LEN) return null;
    return preg_match('~^[' . REF_ALPHABET . ']+$~', $code) ? $code : null;
}

/**
 * Можно ли записать, что $inviterId привёл $inviteeId.
 *
 * Возвращает ['ok' => bool, 'reason' => string]: причина нужна не человеку,
 * а нам — в отчёте видно, почему приглашение не засчиталось, и это разница
 * между «программа не работает» и «программа работает, а код был свой».
 *
 * $inviteeExisted — была ли строка человека в базе ДО этого захода.
 */
function ref_can_attribute(?string $inviterId, string $inviteeId, bool $inviteeExisted, ?string $alreadyInvitedBy): array
{
    if ($inviterId === null || $inviterId === '') return ['ok' => false, 'reason' => 'кода нет'];
    if ($inviteeId === '') return ['ok' => false, 'reason' => 'нет приглашённого'];
    // Сам себя привести нельзя — это не осторожность, а первое, что сделает
    // всякий, кто увидит, что за приглашения что-то дают.
    if ($inviterId === $inviteeId) return ['ok' => false, 'reason' => 'код свой собственный'];
    // Только при регистрации. Иначе человек, уже год работающий у нас, в
    // любой момент «вспомнил» бы, кто его привёл, — и привёл бы кто угодно.
    if ($inviteeExisted) return ['ok' => false, 'reason' => 'человек уже был зарегистрирован'];
    // Приглашение записывается один раз и навсегда.
    if ($alreadyInvitedBy !== null && $alreadyInvitedBy !== '') {
        return ['ok' => false, 'reason' => 'приглашение уже записано'];
    }
    return ['ok' => true, 'reason' => ''];
}

// Итоги смены, которые что-то говорят о поручительстве. Отмена — не говорит:
// смену отменили, и кто был прав, из строки не видно. Записать отмену как
// невыход значило бы испортить поручителю разрыв за то, чего не было.
const REF_OUTCOMES = ['worked', 'no_show'];

/**
 * Записывается ли этот итог смены в поручительство.
 *
 * $outcome        — итог из jm_likes: 'worked' или 'no_show', остальные нет;
 * $invitedBy      — кто привёл этого работника, null если никто;
 * $workerId       — сам работник;
 * $vouchExists    — есть ли уже запись о первой смене этого работника.
 */
function ref_should_record(string $outcome, ?string $invitedBy, string $workerId, bool $vouchExists, ?string $employerId = null): array
{
    // Ни отклик, ни матч, ни выход на связь — только состоявшаяся или
    // несостоявшаяся смена. См. заголовок файла.
    if (!in_array($outcome, REF_OUTCOMES, true)) return ['ok' => false, 'reason' => 'итог смены не решён'];
    if ($invitedBy === null || $invitedBy === '') return ['ok' => false, 'reason' => 'работника никто не приводил'];
    if ($invitedBy === $workerId) return ['ok' => false, 'reason' => 'приглашение само на себя'];
    // Записываем ПЕРВУЮ смену приглашённого, а не каждую. Иначе поручитель
    // копил бы чужой стаж как свой, и число на его карточке рассказывало бы
    // о трудолюбии приведённого, а не о том, кого он умеет звать.
    if ($vouchExists) return ['ok' => false, 'reason' => 'первая смена этого работника уже записана'];
    // Пригласивший не может быть работодателем той самой смены. Иначе это
    // замкнутый круг: работодатель зовёт работника, нанимает его, сам
    // закрывает смену как отработанную и сам себе поднимает поручительство.
    // Ни одного постороннего в этой цепочке нет, а значит нет и того, за что
    // мы ручаемся, — приведённого со стороны человека.
    if ($employerId !== null && $employerId !== '' && $invitedBy === $employerId) {
        return ['ok' => false, 'reason' => 'пригласивший — работодатель этой смены'];
    }
    return ['ok' => true, 'reason' => ''];
}
